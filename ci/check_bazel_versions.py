"""Checks that every copy of the Bazel versions agrees with its source.

`.bazelversion` is the default Bazel version, which generates the lockfiles, and `ci/bazel_versions.json` lists every
version that CI tests; the lowest one is the supported minimum. The files in `COPIES` and the BCR presubmit must repeat
these versions because their formats cannot read them.
"""

import json
import pathlib
import re
import sys

DEFAULT_SOURCE = ".bazelversion"
TESTED_SOURCE = "ci/bazel_versions.json"
PRESUBMIT = ".bcr/presubmit.yml"
VERSION = re.compile(r"\d+\.\d+\.\d+")

# Each copy is a file, a pattern whose group captures one version, and the versions that all matches must list.
COPIES = (
    ("e2e/smoke/.bazelversion", r"\A(\S+)\n\Z", "default"),
    ("MODULE.bazel", r'">=\s*([\d.]*\d)"', "minimum"),
    ("README.md", r"The minimum is ([\d.]*\d)\.", "minimum"),
)
# A presubmit task is an entry under `tasks:`; its block ends at the next entry at the same indentation.
_PRESUBMIT_TASK = re.compile(r"^    \w+:\n((?:(?:      .*)?\n)*)", re.MULTILINE)
_PRESUBMIT_BAZEL = re.compile(r'^\s*bazel: "([^"]*)"$', re.MULTILINE)


def version_key(version: str) -> tuple[int, ...]:
    """Returns a sort key that orders versions numerically."""
    return tuple(int(part) for part in version.split("."))


def load_versions(root: pathlib.Path) -> dict[str, list[str]]:
    """Reads the sources and returns the expected versions per role.

    Raises:
        ValueError: The sources are malformed or the default version is not tested.
    """
    default = (root / DEFAULT_SOURCE).read_text(encoding="utf-8").strip()
    tested = json.loads((root / TESTED_SOURCE).read_text(encoding="utf-8"))
    if not isinstance(tested, list) or not tested:
        raise ValueError(f"{TESTED_SOURCE} must be a non-empty list of versions")
    for version in [default, *tested]:
        if not isinstance(version, str) or not VERSION.fullmatch(version):
            raise ValueError(f"not a Bazel version: {version!r}")
    if default not in tested:
        raise ValueError(f"{DEFAULT_SOURCE} version {default} is missing from {TESTED_SOURCE}")
    return {"default": [default], "minimum": [min(tested, key=version_key)], "tested": tested}


def check_copies(root: pathlib.Path, versions: dict[str, list[str]]) -> list[str]:
    """Returns an error for every file in `COPIES` whose versions differ from the sources."""
    errors = []
    for path, pattern, role in COPIES:
        text = (root / path).read_text(encoding="utf-8")
        actual = re.findall(pattern, text, flags=re.MULTILINE)
        if actual != versions[role]:
            errors.append(f"{path}: expected {role} Bazel versions {versions[role]}, found {actual}")
    return errors


def check_presubmit(root: pathlib.Path, versions: dict[str, list[str]]) -> list[str]:
    """Returns errors unless the presubmit tests every version and only the default one with the strict lockfile.

    The committed lockfiles are generated by the default version, so only that version can check them strictly.
    """
    _, _, task_text = (root / PRESUBMIT).read_text(encoding="utf-8").partition("\n  tasks:\n")
    tasks = _PRESUBMIT_TASK.findall(task_text)
    tested = [version for task in tasks for version in _PRESUBMIT_BAZEL.findall(task)]
    strict_tasks = [task for task in tasks if "--lockfile_mode=error" in task]
    strict = [version for task in strict_tasks for version in _PRESUBMIT_BAZEL.findall(task)]
    errors = []
    if tested != versions["tested"]:
        errors.append(f"{PRESUBMIT}: expected tested Bazel versions {versions['tested']}, found {tested}")
    if strict != versions["default"]:
        errors.append(f"{PRESUBMIT}: expected strict-lockfile Bazel versions {versions['default']}, found {strict}")
    return errors


def main() -> int:
    """Checks the repository in the current directory and reports every inconsistency."""
    root = pathlib.Path.cwd()
    try:
        versions = load_versions(root)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    errors = check_copies(root, versions) + check_presubmit(root, versions)
    for message in errors:
        print(message, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
